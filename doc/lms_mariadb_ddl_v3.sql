CREATE TABLE COURSE (
    COURSE_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '훈련과정 ID',
    TRAINING_JOB_CATEGORY_ID BIGINT NULL COMMENT '훈련직종분류 ID',
    EDUCATION_CATEGORY_ID BIGINT NULL COMMENT '교육과정분류 ID',
    COURSE_NAME VARCHAR(200) NOT NULL COMMENT '훈련과정명',
    COURSE_TYPE VARCHAR(50) NULL COMMENT '훈련과정 구분',
    COURSE_DIVISION VARCHAR(100) NULL COMMENT '과정명 구분',
    COURSE_COLOR VARCHAR(20) NULL DEFAULT '#000000' COMMENT '과정명 색상',
    DESCRIPTION TEXT NULL COMMENT '훈련과정 설명',
    TOTAL_HOURS INT NULL DEFAULT 0 COMMENT '총 훈련시간',
    INTRODUCTION LONGTEXT NULL COMMENT '과정소개',
    QUALIFICATION LONGTEXT NULL COMMENT '지원자격',
    TUITION_REFUND_INFO LONGTEXT NULL COMMENT '교육비/환급금액',
    CURRICULUM_CONTENT LONGTEXT NULL COMMENT '교육내용',
    CAREER_PATH LONGTEXT NULL COMMENT '수료 후 진로',
    RELATED_CERTIFICATION LONGTEXT NULL COMMENT '관련자격증',
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y' COMMENT '사용 여부',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    CREATED_BY BIGINT NULL COMMENT '등록자 ID',
    UPDATED_AT DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    UPDATED_BY BIGINT NULL COMMENT '수정자 ID',
    PRIMARY KEY (COURSE_ID),
    KEY IDX_COURSE_TRAINING_JOB_CATEGORY (TRAINING_JOB_CATEGORY_ID),
    KEY IDX_COURSE_EDUCATION_CATEGORY (EDUCATION_CATEGORY_ID),
    KEY IDX_COURSE_NAME (COURSE_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE COURSE_BATCH (
    COURSE_ID BIGINT NOT NULL COMMENT '훈련과정 ID',
    BATCH_ID BIGINT NOT NULL COMMENT '훈련기수 ID',
    BATCH_NO INT NULL COMMENT '기수 번호',
    BATCH_NAME VARCHAR(200) NULL COMMENT '기수명',
    CAMPUS_ID BIGINT NULL COMMENT '캠퍼스 ID',
    TRAINING_CODE VARCHAR(100) NULL COMMENT '훈련코드',
    STATUS VARCHAR(30) NULL COMMENT '기수 상태',
    RECRUIT_TYPE VARCHAR(30) NULL COMMENT '모집분류',
    START_DATE DATE NULL COMMENT '훈련 시작일',
    END_DATE DATE NULL COMMENT '훈련 종료일',
    RECRUIT_COUNT INT NULL DEFAULT 0 COMMENT '모집 인원',
    APPROVAL_COUNT INT NULL DEFAULT 0 COMMENT '승인 인원',
    TUITION_AMOUNT DECIMAL(12,2) NULL DEFAULT 0 COMMENT '수강료',
    TUITION_VISIBLE_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '수강료 노출 여부',
    GOV_SUPPORT_AMOUNT DECIMAL(12,2) NULL DEFAULT 0 COMMENT '정부지원금',
    SELF_PAYMENT_DESC TEXT NULL COMMENT '본인부담금 설명',
    ALLOWANCE_TYPE VARCHAR(30) NULL COMMENT '훈련수당 지급타입',
    ALLOWANCE_AMOUNT DECIMAL(12,2) NULL DEFAULT 0 COMMENT '훈련수당',
    ALLOWANCE_DESC TEXT NULL COMMENT '수강료/훈련수당 설명',
    REPRESENTATIVE_FILE_ID BIGINT NULL COMMENT '대표이미지 파일 ID',
    CLASS_START_TIME TIME NULL COMMENT '수업 시작시간',
    CLASS_END_TIME TIME NULL COMMENT '수업 종료시간',
    DAILY_HOURS DECIMAL(5,2) NULL COMMENT '하루 수업시간',
    TRAINING_DAYS INT NULL DEFAULT 0 COMMENT '수업일수',
    TRAINING_PLACE VARCHAR(300) NULL COMMENT '교육장소',
    HRD_LINK VARCHAR(1000) NULL COMMENT 'HRD 링크',
    STUDENT_RECORD_OPEN_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '생기부 오픈 여부',
    LEDGER_VISIBLE_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '운영대장 출력 여부',
    CLICK_COUNT INT NOT NULL DEFAULT 0 COMMENT '조회수',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    CREATED_BY BIGINT NULL COMMENT '등록자 ID',
    UPDATED_AT DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    UPDATED_BY BIGINT NULL COMMENT '수정자 ID',
    PRIMARY KEY (COURSE_ID, BATCH_ID),
    KEY IDX_COURSE_BATCH_CAMPUS (CAMPUS_ID),
    KEY IDX_COURSE_BATCH_STATUS (STATUS),
    KEY IDX_COURSE_BATCH_PERIOD (START_DATE, END_DATE),
    KEY IDX_COURSE_BATCH_TRAINING_CODE (TRAINING_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

