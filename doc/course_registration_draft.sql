-- Apply once before using the registration draft APIs. Existing six tables are unchanged.
CREATE TABLE COURSE_REGISTRATION_DRAFT (
    DRAFT_ID BIGINT NOT NULL AUTO_INCREMENT,
    COURSE_ID BIGINT NOT NULL,
    BATCH_ID BIGINT NULL,
    PAYLOAD LONGTEXT NOT NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (DRAFT_ID),
    KEY IDX_COURSE_DRAFT_BATCH (COURSE_ID, BATCH_ID),
    CONSTRAINT CHK_COURSE_DRAFT_JSON CHECK (JSON_VALID(PAYLOAD))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
