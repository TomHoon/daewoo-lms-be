
-- ============================================================
-- LMS MariaDB DDL v2
-- 기준: 현재까지 만든 화면/업무 흐름
--
-- 핵심 흐름
-- 1. 과정분류 관리
-- 2. 교육과정 등록
-- 3. 입학접수 간편입력 -> 접수자/훈련생 관리
-- 4. NCS 평가항목 등록
-- 5. 평가등록 -> 평가지등록 -> 사전/중간/최종/재평가
-- 6. 설문조사 등록
-- 7. 설문지를 훈련생에게 공유 -> 응답/답변
--
-- 설계 원칙
-- * MariaDB / InnoDB / utf8mb4
-- * FK 제약조건은 두지 않음
-- * 기존 COURSE_ID + BATCH_ID 구조 최대한 유지
-- * 공개설문 지원을 위해 SURVEY는 SURVEY_ID 단일 PK
-- ============================================================

SET NAMES utf8mb4;

-- ============================================================
-- 00. 공통코드 / 파일
-- ============================================================

CREATE TABLE COMMON_CODE_GROUP (
    CODE_GROUP_ID      VARCHAR(50)  NOT NULL COMMENT '공통코드 그룹 ID',
    CODE_GROUP_NAME    VARCHAR(100) NOT NULL COMMENT '공통코드 그룹명',
    DESCRIPTION        VARCHAR(500) NULL COMMENT '설명',
    USE_YN             CHAR(1)      NOT NULL DEFAULT 'Y' COMMENT '사용 여부',
    CREATED_AT         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT         DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (CODE_GROUP_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE COMMON_CODE (
    CODE_GROUP_ID      VARCHAR(50)  NOT NULL COMMENT '공통코드 그룹 ID',
    CODE_ID            VARCHAR(50)  NOT NULL COMMENT '공통코드 ID',
    CODE_NAME          VARCHAR(100) NOT NULL COMMENT '공통코드명',
    CODE_VALUE         VARCHAR(200) NULL COMMENT '공통코드 값',
    SORT_ORDER         INT          NULL DEFAULT 0 COMMENT '정렬 순서',
    USE_YN             CHAR(1)      NOT NULL DEFAULT 'Y' COMMENT '사용 여부',
    CREATED_AT         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT         DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (CODE_GROUP_ID, CODE_ID),
    KEY IDX_COMMON_CODE_USE (CODE_GROUP_ID, USE_YN, SORT_ORDER)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE FILES (
    FILE_ID             BIGINT        NOT NULL AUTO_INCREMENT COMMENT '파일 ID',
    REF_TYPE            VARCHAR(50)   NULL COMMENT '참조 업무 구분',
    REF_ID              BIGINT        NULL COMMENT '참조 데이터 ID',
    ORIGINAL_FILE_NAME  VARCHAR(255)  NULL COMMENT '원본 파일명',
    SAVED_FILE_NAME     VARCHAR(255)  NULL COMMENT '저장 파일명',
    FILE_PATH           VARCHAR(1000) NULL COMMENT '파일 저장 경로',
    FILE_SIZE           BIGINT        NULL COMMENT '파일 크기',
    FILE_EXTENSION      VARCHAR(20)   NULL COMMENT '확장자',
    MIME_TYPE           VARCHAR(100)  NULL COMMENT 'MIME TYPE',
    CREATED_AT          DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY          BIGINT        NULL COMMENT '등록자 ID',
