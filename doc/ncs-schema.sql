-- Reference schema for a NEW database. Do not run against existing tables.
-- SUBJECT is shared by COURSE; NCS units and elements are scoped to BATCH.

CREATE TABLE SUBJECT (
    COURSE_ID          BIGINT       NOT NULL,
    SUBJECT_ID         BIGINT       NOT NULL,
    SUBJECT_NAME       VARCHAR(200) NOT NULL,
    SUBJECT_TYPE       VARCHAR(50)  NULL,
    TRAINING_HOURS     INT          NULL DEFAULT 0,
    SORT_ORDER         INT          NULL DEFAULT 0,
    USE_YN             CHAR(1)      NOT NULL DEFAULT 'Y',
    CREATED_AT         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY         BIGINT       NULL,
    UPDATED_AT         DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UPDATED_BY         BIGINT       NULL,
    PRIMARY KEY (COURSE_ID, SUBJECT_ID),
    KEY IDX_SUBJECT_SORT (COURSE_ID, SORT_ORDER)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE NCS_UNIT (
    COURSE_ID          BIGINT       NOT NULL,
    BATCH_ID           BIGINT       NOT NULL,
    SUBJECT_ID         BIGINT       NOT NULL,
    UNIT_ID            BIGINT       NOT NULL COMMENT '능력단위 ID',
    UNIT_NAME          VARCHAR(250) NOT NULL COMMENT '능력단위명',
    CLASSIFICATION_NO  VARCHAR(100) NULL COMMENT '분류번호',
    TRAINING_HOURS     INT          NULL DEFAULT 0,
    NON_NCS_YN         CHAR(1)      NOT NULL DEFAULT 'N',
    PRE_ASSESSMENT_YN  CHAR(1)      NOT NULL DEFAULT 'N',
    MIXED_TYPE_YN      CHAR(1)      NOT NULL DEFAULT 'N',
    SORT_ORDER         INT          NOT NULL DEFAULT 0,
    USE_YN             CHAR(1)      NOT NULL DEFAULT 'Y',
    CREATED_AT         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY         BIGINT       NULL,
    UPDATED_AT         DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UPDATED_BY         BIGINT       NULL,
    PRIMARY KEY (COURSE_ID, BATCH_ID, SUBJECT_ID, UNIT_ID),
    KEY IDX_NCS_UNIT_SORT (COURSE_ID, BATCH_ID, SUBJECT_ID, SORT_ORDER)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE NCS_UNIT_ELEMENT (
    COURSE_ID          BIGINT       NOT NULL,
    BATCH_ID           BIGINT       NOT NULL,
    SUBJECT_ID         BIGINT       NOT NULL,
    UNIT_ID            BIGINT       NOT NULL,
    ELEMENT_ID         BIGINT       NOT NULL COMMENT '능력단위 요소 ID',
    ELEMENT_NAME       VARCHAR(300) NOT NULL,
    SORT_ORDER         INT          NOT NULL DEFAULT 0,
    USE_YN             CHAR(1)      NOT NULL DEFAULT 'Y',
    CREATED_AT         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY         BIGINT       NULL,
    UPDATED_AT         DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UPDATED_BY         BIGINT       NULL,
    PRIMARY KEY (COURSE_ID, BATCH_ID, SUBJECT_ID, UNIT_ID, ELEMENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
